def collect_times_events(
    groups: Dict[str, List[dict]],
    plotted_strategies: List[str],
) -> Dict[str, Tuple[List[float], List[int]]]:
    out: Dict[str, Tuple[List[float], List[int]]] = {}
    for strat in plotted_strategies:
        rows = []
        for k, v in groups.items():
            if k.upper() == strat.upper():
                rows = v
                break
        times = [float(r["time"]) for r in rows if r["time"] != ""]
        events = [int(r["event"]) for r in rows if r["time"] != ""]
        if times:
            out[strat] = (times, events)
    return out


def load_prepared_groups(csv_path: Path) -> Tuple[Dict[str, List[dict]], List[dict]]:
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Prepared in-vitro KM table not found: {csv_path}\n"
            "Run ef_Figure_4_prepare_plot_data.py on the data computer first."
        )
    groups: Dict[str, List[dict]] = defaultdict(list)
    with open(csv_path, "r", newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    for row in rows:
        row["time"] = float(row["time"])
        row["event"] = int(row["event"])
        groups[row["strategy"]].append(row)
    return groups, rows


def logrank_p_value(times_a: List[float], events_a: List[int], times_b: List[float], events_b: List[int]) -> float:
    """
    Two-sample log-rank test p-value (chi-square with 1 d.f.).
    Returns NaN if variance cannot be computed.
    """
    event_times = sorted({
        t for t, e in zip(times_a, events_a) if e == 1
    } | {
        t for t, e in zip(times_b, events_b) if e == 1
    })

    if not event_times:
        return float("nan")

    sum_oe = 0.0
    sum_var = 0.0

    for t in event_times:
        n1 = sum(1 for x in times_a if x >= t)
        n2 = sum(1 for x in times_b if x >= t)
        n = n1 + n2
        if n <= 1:
            continue

        d1 = sum(1 for x, e in zip(times_a, events_a) if x == t and e == 1)
        d2 = sum(1 for x, e in zip(times_b, events_b) if x == t and e == 1)
        d = d1 + d2
        if d == 0:
            continue

        e1 = d * (n1 / n)
        var = (n1 * n2 * d * (n - d)) / (n * n * (n - 1))

        sum_oe += (d1 - e1)
        sum_var += var

    if sum_var <= 0:
        return float("nan")

    chi2 = (sum_oe ** 2) / sum_var
    # Chi-square(df=1) survival function: p = erfc(sqrt(x/2))
    return float(math.erfc(math.sqrt(max(chi2, 0.0) / 2.0)))


def write_pairwise_logrank_csv(
    groups: Dict[str, List[dict]],
    plotted_strategies: List[str],
    out_csv: Path,
) -> None:
    per_strat = collect_times_events(groups, plotted_strategies)
    available = [s for s in plotted_strategies if s in per_strat]
    pairs = list(combinations(available, 2))

    rows: List[dict] = []
    raw_ps: List[float] = []

    for a, b in pairs:
        t_a, e_a = per_strat[a]
        t_b, e_b = per_strat[b]
        p_val = logrank_p_value(t_a, e_a, t_b, e_b)
        raw_ps.append(p_val)
        rows.append({
            "strategy_a": a,
            "display_a": DISPLAY_NAME.get(a, a),
            "n_a": len(t_a),
            "events_a": int(sum(e_a)),
            "strategy_b": b,
            "display_b": DISPLAY_NAME.get(b, b),
            "n_b": len(t_b),
            "events_b": int(sum(e_b)),
            "p_value": p_val,
            "p_value_bonferroni": "",
            "significant_0_05_bonferroni": "",
        })

    m = len(rows)
    for i, row in enumerate(rows):
        p = raw_ps[i]
        if p == p:  # not NaN
            p_bonf = min(1.0, p * m) if m > 0 else p
            row["p_value_bonferroni"] = p_bonf
            row["significant_0_05_bonferroni"] = int(p_bonf < 0.05)

    with open(out_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "strategy_a",
                "display_a",
                "n_a",
                "events_a",
                "strategy_b",
                "display_b",
                "n_b",
                "events_b",
                "p_value",
                "p_value_bonferroni",
                "significant_0_05_bonferroni",
            ],
        )
        writer.writeheader()
        writer.writerows(rows)

    print(f"[OK] Wrote non-trunc pairwise log-rank tests: {out_csv}")


def print_pairwise_logrank_statistics(
    groups: Dict[str, List[dict]],
    plotted_strategies: List[str],
    label: str,
) -> None:
    """Print pairwise log-rank statistics for the exact cohort being plotted."""
    per_strat = collect_times_events(groups, plotted_strategies)
    available = [strategy for strategy in plotted_strategies if strategy in per_strat]
    results = []
    for strategy_a, strategy_b in combinations(available, 2):
        times_a, events_a = per_strat[strategy_a]
        times_b, events_b = per_strat[strategy_b]
        results.append((
            strategy_a,
            strategy_b,
            len(times_a),
            int(sum(events_a)),
            len(times_b),
            int(sum(events_b)),
            logrank_p_value(times_a, events_a, times_b, events_b),
        ))
    print(f"[MANUSCRIPT STATS] Figure 4e pairwise log-rank tests ({label}; displayed cohort):")
    comparison_count = len(results)
    for strategy_a, strategy_b, n_a, events_a, n_b, events_b, p_value in results:
        adjusted = min(1.0, p_value * comparison_count) if np.isfinite(p_value) else np.nan
        print(
            f"  {DISPLAY_NAME.get(strategy_a, strategy_a)} vs "
            f"{DISPLAY_NAME.get(strategy_b, strategy_b)}: "
            f"n/events={n_a}/{events_a} vs {n_b}/{events_b}; "
            f"p={p_value:.6g}; Bonferroni p={adjusted:.6g}"
        )


def plot_km_on_axis(
    ax: plt.Axes,
    groups: Dict[str, List[dict]],
    plotted_strategies: List[str],
    color_map: Dict[str, str],
    linestyle: str = "-",
) -> None:
    per_strat_times: Dict[str, List[float]] = {}
    per_strat_events: Dict[str, List[int]] = {}

    for strat in plotted_strategies:
        rows = []
        for k, v in groups.items():
            if k.upper() == strat.upper():
                rows = v
                break
        times = [float(r["time"]) for r in rows if r["time"] != ""]
        events = [int(r["event"]) for r in rows if r["time"] != ""]
        if not times:
            continue
        per_strat_times[strat] = times
        per_strat_events[strat] = events

    for strat in plotted_strategies:
        if strat not in per_strat_times:
            continue

        times = per_strat_times[strat]
        events = per_strat_events[strat]

        t_vals, surv_vals = kaplan_meier_fit(times, events)
        # Show the final estimated survival level only through this strategy's
        # own last observed follow-up (event or censoring), never through the
        # longer follow-up of another strategy.
        strategy_max = max(times)
        if surv_vals[-1] > 0 and t_vals[-1] < strategy_max:
            t_vals = list(t_vals) + [float(strategy_max)]
            surv_vals = list(surv_vals) + [float(surv_vals[-1])]

        display = DISPLAY_NAME.get(strat, strat)
        line, = ax.plot(
            t_vals,
            surv_vals,
            drawstyle="steps-post",
            linewidth=LINEWIDTH,
            color=color_map[strat],
            linestyle=linestyle,
            dash_capstyle="round",
            label=f"{display} (n={len(times)})",
        )

        censored_times = [t for t, e in zip(times, events) if e == 0]
        for ct in censored_times:
            y = survival_at_time(t_vals, surv_vals, ct)
            ax.plot(
                ct, y,
                marker="|",
                markersize=8,
                markeredgewidth=LINEWIDTH * 0.5,
                color=line.get_color(),
            )

    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.tick_params(direction="out")
    ax.set_xlabel("Acquisition day")
    ax.set_ylabel("Failure-free fraction")
    ax.set_ylim(0, 1.05)
    ax.set_xlim(0, KM_X_AXIS_MAX_DAYS)
    ax.set_xticks([0, 20, 40, 60, 80, 100, 120])



