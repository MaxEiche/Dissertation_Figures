def _stored_count(node) -> int:
    if isinstance(node, h5py.Dataset):
        return int(node.shape[0]) if node.ndim else int(node[()])
    for name in ("block0_values", "values"):
        if name in node:
            return int(node[name].shape[0])
    raise ValueError(f"Cannot count cells in HDF5 node {node.name}")


def _add_dens_trajectories(groups: dict[str, list[dict]], rows: list[dict]) -> None:
    if not SIMULATION_MANIFEST.is_file():
        raise FileNotFoundError(f"Simulation manifest not found: {SIMULATION_MANIFEST}")
    manifest = pd.read_csv(SIMULATION_MANIFEST, sep="\t", dtype=str)
    dens = manifest[manifest["strategy"].str.upper().eq("DENS")].copy()
    dens["run_number"] = pd.to_numeric(dens["run_id"].str.extract(r"(\d+)$", expand=False), errors="coerce")
    for record in dens[dens["run_number"] >= MIN_RUN_NUMBER].itertuples(index=False):
        path = Path(record.prepared_hdf5_path)
        if not path.is_file():
            raise FileNotFoundError(f"Processed AT100+ trajectory not found: {path}")
        with h5py.File(path, "r") as handle:
            keys = sorted(set(handle["sus"].keys()) & set(handle["res"].keys()))
            counts = [(float(int(key.rsplit("_", 1)[-1])), _stored_count(handle["sus"][key]) + _stored_count(handle["res"][key]), _stored_count(handle["res"][key])) for key in keys]
        if not counts or counts[0][1] <= 0:
            continue
        hits = [day for day, _total, resistant in counts if resistant / counts[0][1] >= THRESHOLD]
        run = int(record.run_number)
        row = {"plate": "simulation", "well": f"run_{run}", "strategy": "Dens", "filepath": str(path),
               "time": float(hits[0] if hits else counts[-1][0]), "event": int(bool(hits)),
               "baseline_total": counts[0][1], "sample_key": f"Dens_run_{run}"}
        groups["Dens"].append(row); rows.append(row)


def build_insilico_groups() -> tuple[dict[str, list[dict]], list[dict]]:
    """Build simulation failure-time rows from raw outputs; used by preparation."""
    if not SIMULATION_CSV.is_file():
        raise FileNotFoundError(f"Simulation summary CSV not found: {SIMULATION_CSV}")
    data = pd.read_csv(SIMULATION_CSV, dtype={"protocol": str})
    required = {"protocol", "run", "day", "normalized_tot", "normalized_sus"}
    missing = required - set(data)
    if missing: raise ValueError(f"Simulation CSV is missing columns: {sorted(missing)}")
    data["protocol_key"] = data["protocol"].str.strip().str.upper(); data["strategy"] = data["protocol_key"].map(PROTOCOL_MAP)
    for column in ("run", "day", "normalized_tot", "normalized_sus"): data[column] = pd.to_numeric(data[column], errors="coerce")
    data = data[data.strategy.notna() & data.run.notna() & (data.run >= MIN_RUN_NUMBER) & data.day.notna()].copy()
    data["normalized_resistant"] = data.normalized_tot - data.normalized_sus
    groups, rows = defaultdict(list), []
    for (protocol, run), trajectory in data.groupby(["protocol_key", "run"], sort=True):
        trajectory = trajectory.sort_values("day").drop_duplicates("day", keep="first").dropna(subset=["normalized_resistant"])
        if trajectory.empty: continue
        hits = trajectory[trajectory.normalized_resistant >= THRESHOLD]
        strategy = PROTOCOL_MAP[protocol]
        row = {"plate": "simulation", "well": f"run_{int(run)}", "strategy": strategy, "filepath": str(SIMULATION_CSV),
               "time": float(hits.iloc[0].day if not hits.empty else trajectory.iloc[-1].day), "event": int(not hits.empty),
               "baseline_total": "normalized", "sample_key": f"{strategy}_run_{int(run)}"}
        groups[strategy].append(row); rows.append(row)
    _add_dens_trajectories(groups, rows)
    if not rows: raise RuntimeError("No eligible simulation trajectories were found.")
    return dict(groups), rows


def write_insilico_summary(rows: list[dict]) -> None:
    with SILICO_SUMMARY_CSV.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0])); writer.writeheader(); writer.writerows(rows)


